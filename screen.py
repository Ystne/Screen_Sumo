"""
Replays a configuration generated by replay.py and takes screenshots using matplotlib.

Usage:
    python screen.py --config replays/replay_ep2400.sumocfg --interval 100
    python screen.py --config replays/replay_ep2400.sumocfg --times 500 1000 2400
"""

import os
import argparse
import traci
import sumolib
import matplotlib.pyplot as plt
import xml.etree.ElementTree as ET

def render(net, vehicles, sim_time, output_dir):
    fig, ax = plt.subplots(figsize=(14, 14))

    # Draw roads
    for edge in net.getEdges():
        for lane in edge.getLanes():
            shape = lane.getShape()
            if len(shape) >= 2:
                xs, ys = zip(*shape)
                ax.plot(xs, ys, color="lightgray", linewidth=0.3, zorder=1)

    # Draw vehicles
    if vehicles:
        xs = [v[0] for v in vehicles]
        ys = [v[1] for v in vehicles]
        ax.scatter(xs, ys, s=12, c="red", zorder=2)

    ax.set_aspect("equal")
    ax.axis("off")

    path = os.path.join(output_dir, f"snapshot_t{int(sim_time)}.png")
    # pad_inches=0 removes any extra white border around the image
    plt.savefig(path, dpi=150, bbox_inches="tight", pad_inches=0)
    plt.close()
    print(f"Screenshot saved: {path}")

def get_sumo_cmd_from_cfg(cfg_path):
    """
    Reads the .sumocfg and extracts absolute paths to avoid 
    duplicate folder resolution errors (e.g., replays/replays/...).
    """
    tree = ET.parse(cfg_path)
    root = tree.getroot()
    
    cfg_dir = os.path.dirname(os.path.abspath(cfg_path))
    cwd = os.getcwd()
    
    cmd = []
    net_file_abs = None

    for elem in root.iter():
        if elem.tag in ["net-file", "route-files", "additional-files"]:
            val = elem.get("value")
            if not os.path.isabs(val):
                # SUMO normally resolves relative to the cfg folder
                path_relative_to_cfg = os.path.abspath(os.path.join(cfg_dir, val))
                # Fallback if generated relative to the current working directory
                path_relative_to_cwd = os.path.abspath(os.path.join(cwd, val))
                
                if os.path.exists(path_relative_to_cfg):
                    val = path_relative_to_cfg
                elif os.path.exists(path_relative_to_cwd):
                    val = path_relative_to_cwd
                else:
                    val = path_relative_to_cfg # Fallback to cfg dir resolution
            
            # Format with forward slashes for SUMO compatibility
            val = val.replace("\\", "/")
            
            if elem.tag == "net-file":
                cmd.extend(["--net-file", val])
                net_file_abs = val
            elif elem.tag == "route-files":
                cmd.extend(["--route-files", val])
            elif elem.tag == "additional-files":
                cmd.extend(["--additional-files", val])
                
    return cmd, net_file_abs

def main():
    parser = argparse.ArgumentParser(description="Replays a SUMO episode and captures screenshots.")
    parser.add_argument("--config", type=str, required=True, help="Path to the .sumocfg file")
    parser.add_argument("--interval", type=int, default=None, help="Screenshot interval in seconds")
    parser.add_argument("--times", type=float, nargs="+", default=None, help="List of exact capture times (in seconds)")
    parser.add_argument("--out", type=str, default="screenshots", help="Output directory for images")
    args = parser.parse_args()

    os.makedirs(args.out, exist_ok=True)

    # 1. Determine capture times
    capture_times = []
    if args.times:
        capture_times.extend(args.times)
    
    # 2. Extract absolute paths from the .sumocfg
    sumo_cmd_args, net_file_abs = get_sumo_cmd_from_cfg(args.config)
    if not net_file_abs:
        raise ValueError("Could not find net-file in the .sumocfg")
    
    net = sumolib.net.readNet(net_file_abs)

    # 3. Start SUMO
    cmd = ["sumo", "-c", args.config] + sumo_cmd_args
    traci.start(cmd)
    
    if args.interval:
        print(f"Capture mode: Every {args.interval}s (+ exact times: {args.times})")
    else:
        print(f"Capture mode: Exact times {args.times}")

    next_interval_capture = args.interval if args.interval else float('inf')
    pending_times = sorted([t for t in capture_times if t > 0])
    
    # Capture at t=0 if requested
    if 0 in capture_times or (args.interval and 0 >= next_interval_capture):
        target = 0
        vehicles = [traci.vehicle.getPosition(v) for v in traci.vehicle.getIDList()]
        render(net, vehicles, target, args.out)

    try:
        while traci.simulation.getMinExpectedNumber() > 0:
            current_time = traci.simulation.getTime()
            
            take_screen = False
            target_time = 0
            
            # Check if an exact time is reached
            if pending_times and current_time >= pending_times[0]:
                target_time = pending_times.pop(0)
                take_screen = True
            
            # Check if the interval is reached
            elif args.interval and current_time >= next_interval_capture:
                target_time = current_time
                take_screen = True
                next_interval_capture += args.interval

            if take_screen:
                vehicles = [traci.vehicle.getPosition(v) for v in traci.vehicle.getIDList()]
                render(net, vehicles, target_time, args.out)

            traci.simulationStep()
            
        final_time = traci.simulation.getTime()

    finally:
        traci.close()

    print("=" * 50)
    print(f"Simulation finished at t={final_time:.1f}s")
    print(f"Screenshots saved in: {args.out}")
    print("=" * 50)

if __name__ == "__main__":
    main()